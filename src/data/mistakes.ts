export function mistakesBySubject(subjectId?: string): Mistake[] {
  if (!subjectId || subjectId === 'all') return MISTAKES
  return MISTAKES.filter((mistake) => mistake.subjectId === subjectId)
}

export function mistakeCounts() {
  const counts = new Map<string, number>()
  for (const mistake of MISTAKES) {
    counts.set(mistake.subjectId, (counts.get(mistake.subjectId) ?? 0) + 1)
  }
  return counts
}
